import xml.etree.ElementTree as ET
import os
from pathlib import Path

def sanitize_filename(name):
    """
    将依赖路径转换为安全的文件名（主要用于处理外部库）。
    移除非法字符，并进行简化。
    """
    # 对于外部库，提取关键信息
    if name.startswith("$MAVEN_REPOSITORY$"):
        # 示例: $MAVEN_REPOSITORY$/com/google/guava/.../Iterables.class
        parts = name.split('/')
        # 找到包含 jar 文件名和类名的部分
        jar_part = None
        class_part = None
        for i, part in enumerate(parts):
            if '.jar!' in part:
                jar_part = part.split('.jar!')[0]  # 如: guava-25.1-jre
                if i + 1 < len(parts):
                    class_part = parts[i + 1].replace('.class', '')  # 如: Iterables
                break
        
        if jar_part and class_part:
            # 提取库名 (如 guava)
            lib_name = jar_part.split('-')[0] if '-' in jar_part else jar_part
            return f"{lib_name}-{class_part}"
        else:
            return "External-Dependency"
    
    # 对于项目内依赖，直接使用，但确保文件名安全
    # 在Obsidian中，文件名通常可以包含点和连字符，我们主要移除可能导致问题的字符
    # 这里我们假设项目内路径是安全的，直接返回
    return name

def create_obsidian_notes_from_xml(xml_file_path, output_dir):
    """
    将XML依赖文件转换为Obsidian笔记库。

    Args:
        xml_file_path (str): 输入的XML文件路径。
        output_dir (str): 输出的Obsidian库根目录路径。
    """
    # 解析XML
    tree = ET.parse(xml_file_path)
    root = tree.getroot()

    # 确保输出目录存在
    Path(output_dir).mkdir(parents=True, exist_ok=True)

    # 用于存储所有需要创建的笔记路径，避免重复创建外部库笔记
    created_notes = set()
    # 用于存储外部库的映射 {原始路径: 简化后的笔记名}
    external_lib_map = {}

    # 第一遍：收集所有节点（文件和依赖项），并处理外部库
    all_paths = set()
    for file_elem in root.findall('file'):
        file_path = file_elem.get('path')
        all_paths.add(file_path)
        
        for dep_elem in file_elem.findall('dependency'):
            dep_path = dep_elem.get('path')
            all_paths.add(dep_path)
            
            # 如果是外部库，生成一个友好的名称
            if dep_path.startswith("$MAVEN_REPOSITORY$"):
                friendly_name = sanitize_filename(dep_path)
                # 确保名称唯一，避免冲突
                counter = 1
                original_friendly = friendly_name
                while friendly_name in external_lib_map.values() or friendly_name in all_paths:
                    friendly_name = f"{original_friendly}_{counter}"
                    counter += 1
                external_lib_map[dep_path] = friendly_name

    # 第二遍：为所有路径创建笔记（包括那些只被依赖但未在<file>中定义的）
    for path in all_paths:
        # 确定最终的笔记文件名
        if path in external_lib_map:
            note_filename = external_lib_map[path]
        else:
            note_filename = path
        
        # 构建完整的文件路径
        full_path = os.path.join(output_dir, note_filename + ".md")
        note_dir = os.path.dirname(full_path)
        
        # 创建目录
        if note_dir:
            Path(note_dir).mkdir(parents=True, exist_ok=True)
        
        # 如果笔记已存在，则跳过创建（但依赖关系会在后面添加）
        if not os.path.exists(full_path):
            with open(full_path, 'w', encoding='utf-8') as f:
                # 写入YAML Front Matter
                f.write("---\n")
                f.write(f"title: {note_filename}\n")
                f.write(f"type: {'external_library' if path in external_lib_map else 'java_class'}\n")
                f.write(f"original_path: {path}\n")
                f.write("---\n\n")
                # 写入标题
                f.write(f"# {note_filename}\n\n")
                # 占位符，依赖关系将在下一步添加
                f.write("## Dependencies\n\n")
                f.write("This file is automatically generated.\n")
            
            created_notes.add(full_path)
            print(f"已创建笔记: {full_path}")

    # 第三遍：为每个<file>填充其依赖关系
    for file_elem in root.findall('file'):
        source_path = file_elem.get('path')
        # 确定源笔记的文件路径
        source_filename = external_lib_map.get(source_path, source_path)
        source_full_path = os.path.join(output_dir, source_filename + ".md")
        
        # 读取现有内容
        with open(source_full_path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        # 找到 "## Dependencies" 部分的末尾
        dep_header_index = content.find("## Dependencies")
        if dep_header_index == -1:
            # 如果没有找到，追加到文件末尾
            new_content = content + "\n\n## Dependencies\n\n"
        else:
            # 找到header后的第一个换行，然后清空其后内容
            end_of_header = content.find("\n", dep_header_index)
            if end_of_header == -1:
                end_of_header = len(content)
            new_content = content[:end_of_header + 1] + "\n"
        
        # 添加所有依赖项
        dependencies = file_elem.findall('dependency')
        if dependencies:
            for dep_elem in dependencies:
                dep_path = dep_elem.get('path')
                # 获取依赖项的笔记名
                dep_note_name = external_lib_map.get(dep_path, dep_path)
                # 添加双向链接
                new_content += f"- [[{dep_note_name}]]\n"
        else:
            new_content += "No dependencies.\n"
        
        # 写回文件
        with open(source_full_path, 'w', encoding='utf-8') as f:
            f.write(new_content)
        
        print(f"已更新依赖关系: {source_full_path}")

    print(f"\n转换完成！Obsidian库已生成在: {output_dir}")
    print(f"共创建了 {len(created_notes)} 个新笔记。")

# 使用示例
# 请将 'converts.local\deps.xml' 替换为您的实际XML文件路径
# 请将 'MyObsidianProject' 替换为您希望的Obsidian库名称
create_obsidian_notes_from_xml('.\\converts.local\\deps.xml', 'MyObsidianProject')
